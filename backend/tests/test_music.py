def tone_video(settings, path: Path, seconds: float = 12.0, speech: list[tuple[float, float]] | None = None) -> Path:
    """A video whose sound is a steady 'voice' (a 300 Hz tone) only during the given ranges."""
    speech = speech if speech is not None else [(1.0, 4.0), (6.0, 9.0)]
    n = int(seconds * SR)
    audio = np.zeros(n, dtype=np.float32)
    for a, b in speech:
        i, j = int(a * SR), int(b * SR)
        audio[i:j] = 0.25 * np.sin(2 * np.pi * 300 * np.arange(j - i) / SR) * (0.8 + 0.2 * np.sin(2 * np.pi * 4 * np.arange(j - i) / SR))
    wav = path.with_suffix(".wav")
    with wave.open(str(wav), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((audio * 32767).astype(np.int16).tobytes())
    subprocess.run(
        [settings.ffmpeg, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i",
         f"color=c=0x303030:s=640x360:r=15:d={seconds}", "-i", str(wav), "-c:v", "libx264", "-preset", "ultrafast",
         "-c:a", "aac", "-shortest", str(path)],
        check=True, capture_output=True, creationflags=NO_WINDOW,
    )
    return path


def decode(settings, path: Path, rate: int = 22050) -> np.ndarray:
    # the first channel only: a stereo-to-mono downmix would add left and right and read 3 dB louder
    raw = subprocess.run(
        [settings.ffmpeg, "-hide_banner", "-loglevel", "error", "-i", str(path), "-vn", "-af", "pan=mono|c0=c0",
         "-ar", str(rate), "-f", "f32le", "-"],
        check=True, capture_output=True, creationflags=NO_WINDOW,
    ).stdout
    return np.frombuffer(raw, dtype=np.float32)


def db(x: np.ndarray) -> float:
    return 20 * np.log10(np.sqrt(np.mean(x.astype(np.float64) ** 2)) + 1e-9)


def test_music_sits_well_under_the_speech_and_the_speech_is_untouched(settings, tmp_path):
    speech = [(1.0, 4.0), (6.0, 9.0)]
    video = tone_video(settings, tmp_path / "v.mp4", speech=speech)
    track = tmp_path / "bed.wav"
    write_click_track(track, bpm=120, seconds=30)
    analysis = mu.analyse_track(settings, track)

    speech_db = mu.level_in_windows(video.with_suffix(".wav"), speech)
    assert analysis["channels"] == 1
    plan = mu.plan_mix(info(loudness_db=analysis["loudness_db"], duration=30.0, beats=[], channels=1), 12.0, None,
                       speech_db, -30.0, 14.0)
    env = mu.write_envelope(tmp_path / "duck.wav", speech, 12.0)
    spec = MixSpec(track, plan["offset"], plan["loop"], plan["gain_db"], plan["fade_in"], plan["fade_out"], env, 1)

    stem = render_music_stem(settings, spec, 12.0, tmp_path / "stem.wav")
    in_speech = mu.level_in_windows(stem, speech)
    in_pause = mu.level_in_windows(stem, mu.silence_gaps(speech, 12.0))
    gap = speech_db - in_speech
    assert gap >= mu.MIN_GAP_DB, f"music only {gap:.1f} dB under the speech"
    assert gap == pytest.approx(14 + mu.DUCK_DB, abs=3.0), "open level (14 dB) plus the duck (10 dB)"
    assert in_pause - in_speech == pytest.approx(mu.DUCK_DB, abs=2.5), "it comes back up between the speech"

    out = render_vertical(settings, video, tmp_path / "mixed.mp4", [(0.0, 12.0)], None, has_audio=True, music=spec,
                          audio_channels=1)
    plain = render_vertical(settings, video, tmp_path / "plain.mp4", [(0.0, 12.0)], None, has_audio=True)
    info_mixed = probe_media(settings, out)
