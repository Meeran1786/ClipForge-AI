def write_click_track(path: Path, bpm: float = 120, seconds: float = 40, first: float = 0.5, accent_every: int = 4,
                      pad: float = 0.04) -> list[float]:
    """A steady click track with a louder, lower thump on every `accent_every`th beat. Returns beat times."""
    n = int(seconds * SR)
    audio = pad * np.sin(2 * np.pi * 220 * np.arange(n) / SR).astype(np.float32)
    beats = []
    k = 0
    t = first
    while t < seconds - 0.2:
        beats.append(round(t, 4))
        i = int(t * SR)
        m = min(int(0.06 * SR), n - i)
        env = np.exp(-np.arange(m) / (0.012 * SR)).astype(np.float32)
        tone = np.arange(m) / SR
        if k % accent_every == 0:
            audio[i:i + m] += 0.8 * env * np.sin(2 * np.pi * 110 * tone) + 0.3 * env * np.sin(2 * np.pi * 1600 * tone)
        else:
            audio[i:i + m] += 0.3 * env * np.sin(2 * np.pi * 1600 * tone)
        k += 1
        t += 60.0 / bpm
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((np.clip(audio, -1, 1) * 32767).astype(np.int16).tobytes())
    return beats


