def test_a_beat_lands_on_the_key_moment_in_the_rendered_music(settings, tmp_path):
    track = tmp_path / "bed.wav"
    write_click_track(track, bpm=120, seconds=60)
    a = mu.analyse_track(settings, track)  # use the beats as the app really finds them
    ti = info(duration=a["duration"], beats=a["beats"], phase=a["phase"], regularity=a["regularity"], bpm=a["bpm"],
              loudness_db=a["loudness_db"])
    anchor = 8.2
    offset, beat, note = mu.align_start(ti, 20.0, anchor)
    assert beat is not None, note
    stem = render_music_stem(settings, MixSpec(track, offset, False, 0.0, 0.1, 0.5, None), 20.0, tmp_path / "s.wav")
    x = np.abs(decode(settings, stem))
    sr = 22050
    smooth = np.convolve(x, np.ones(int(0.004 * sr)) / int(0.004 * sr), mode="same")
    window = slice(int((anchor - 0.2) * sr), int((anchor + 0.2) * sr))
    peak_time = (window.start + int(np.argmax(smooth[window]))) / sr
    assert abs(peak_time - anchor) <= 0.02, f"the loudest beat is {abs(peak_time - anchor) * 1000:.0f} ms from the key moment"
    # it is the bar's strong beat, not any beat: the thump is clearly louder than its neighbours
    neighbour = slice(int((anchor + 0.3) * sr), int((anchor + 0.7) * sr))
    assert smooth[window].max() > 1.8 * smooth[neighbour].max()


