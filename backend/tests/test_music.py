def test_tempo_beats_and_level_are_read_from_the_audio(settings, tmp_path):
    truth = write_click_track(tmp_path / "t.wav", bpm=120, seconds=40)
    a = mu.analyse_track(settings, tmp_path / "t.wav")
    assert a["duration"] == pytest.approx(40.0, abs=0.1)
    assert a["bpm"] == pytest.approx(120.0, abs=2.0)
    assert a["regularity"] >= mu.BEAT_REGULARITY_MIN
    # Every detected beat is within 15 ms of a real one, with no systematic lag. (Before the attacks were
    # snapped, every beat came out about 25 ms late: spread was small, so only the mean showed it.)
    found = np.array(a["beats"])
    signed = np.array([float(found_b - truth[int(np.argmin(np.abs(np.array(truth) - found_b)))]) for found_b in found])
    assert np.abs(signed).max() <= 0.015, f"worst beat error {np.abs(signed).max() * 1000:.0f} ms"
    assert abs(signed.mean()) <= 0.008, f"beats are {signed.mean() * 1000:+.0f} ms off on average"
    assert len(found) >= 0.9 * len(truth)
    # the louder thump marks the first beat of each bar
    first_beats = [truth[k] for k in range(0, len(truth), 4)]
    start_of_bar = found[a["phase"]::4]
    assert np.mean([float(np.min(np.abs(np.array(first_beats) - b))) for b in start_of_bar]) <= 0.015
    assert -40 < a["loudness_db"] < -10


def test_beats_over_a_drone_have_no_systematic_lag(settings, tmp_path):
    """A drone with soft ticks has no sharp attacks to snap to. The tracker's own lag (about 25 ms, seen
    on every track measured) must still be taken off, or a bar line lands late on the key moment."""
    n = 60 * SR
    t = np.arange(n) / SR
    rng = np.random.default_rng(5)
    audio = (0.3 * np.sin(2 * np.pi * 55 * t) * (0.7 + 0.3 * np.sin(2 * np.pi * 0.13 * t))).astype(np.float32)
    period, first, truth = 60 / 80, 0.4, []
    k = 0
    while first + k * period < 59.5:
        b = first + k * period
        truth.append(b)
        i, m = int(b * SR), int(0.03 * SR)
        audio[i:i + m] += (0.35 * rng.standard_normal(m) * np.exp(-np.arange(m) / (0.008 * SR))).astype(np.float32)
        if k % 4 == 0:
            audio[i:i + int(0.3 * SR)] += (0.4 * np.sin(2 * np.pi * 60 * t[:int(0.3 * SR)]) * np.exp(-np.arange(int(0.3 * SR)) / (0.05 * SR))).astype(np.float32)
        k += 1
    path = tmp_path / "drone_ticks.wav"
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((np.clip(audio, -1, 1) * 32767).astype(np.int16).tobytes())
    a = mu.analyse_track(settings, path)
    assert a["beats"], "the ticks are a steady beat"
    grid = np.array(truth)
    signed = np.array([b - grid[int(np.argmin(np.abs(grid - b)))] for b in a["beats"]])
    assert abs(signed.mean()) <= 0.012, f"beats are {signed.mean() * 1000:+.0f} ms off on average"
    assert np.abs(signed).max() <= 0.03


def test_a_track_with_no_beat_has_no_beats_to_line_up(settings, tmp_path):
    n = 30 * SR
    rng = np.random.default_rng(3)
    drone = (0.05 * np.sin(2 * np.pi * 180 * np.arange(n) / SR) * (1 + 0.2 * np.sin(2 * np.pi * 0.1 * np.arange(n) / SR))
             + 0.003 * rng.standard_normal(n)).astype(np.float32)
    with wave.open(str(tmp_path / "drone.wav"), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((drone * 32767).astype(np.int16).tobytes())
    a = mu.analyse_track(settings, tmp_path / "drone.wav")
    steady = bool(a["beats"]) and a["regularity"] >= mu.BEAT_REGULARITY_MIN
    assert not steady, "a drone must not be treated as having a beat to line up"


