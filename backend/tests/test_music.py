@pytest.mark.parametrize("seed", range(40))
def test_alignment_always_puts_a_beat_on_the_anchor_and_stays_inside_the_track(seed):
    rng = random.Random(seed)
    bpm = rng.uniform(70, 170)
    step = 60 / bpm
    first = rng.uniform(0, 1.5)
    duration = rng.uniform(30, 200)
    beats = [round(first + k * step, 3) for k in range(int((duration - first) / step))]
    track = info(duration=duration, beats=beats, phase=rng.randrange(4), bpm=bpm)
    clip_len = rng.uniform(10, 25)
    anchor = rng.uniform(0.2, clip_len - 0.2)
    offset, beat, note = mu.align_start(track, clip_len, anchor)
    assert offset >= 0 and offset + clip_len <= duration + 1e-6
    if beat is not None:
        assert any(abs((offset + anchor) - b) < 1e-3 for b in beats), "a real beat is under the key moment"
        if beat["kind"] == "downbeat":
            assert beat["beat_time"] in beats[track.phase::4]
        assert offset == pytest.approx(beat["beat_time"] - anchor, abs=1e-3)
    else:
        assert offset == 0.0 and note


